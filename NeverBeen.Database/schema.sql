-- Derive the 20-digit UniqueId automatically ('8920153401' + lpad(Id, 10, '0')).
CREATE OR REPLACE FUNCTION neverbeen_set_user_unique_id() RETURNS trigger AS $$
BEGIN
    IF NEW."UniqueId" IS NULL OR NEW."UniqueId" = '' THEN
        NEW."UniqueId" := '8920153401' || lpad(NEW."Id"::text, 10, '0');
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS "TR_Users_UniqueId" ON "Users";
CREATE TRIGGER "TR_Users_UniqueId"
    BEFORE INSERT ON "Users"
    FOR EACH ROW EXECUTE FUNCTION neverbeen_set_user_unique_id();

