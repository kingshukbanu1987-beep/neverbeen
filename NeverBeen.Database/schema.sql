-- ============================================================================
-- NeverBeen Community — Supabase (PostgreSQL) schema
-- ----------------------------------------------------------------------------
-- Creates every table used by the NeverBeen Community API (.NET 7 Web API):
-- sign in / sign up (users + OAuth identities), profiles, settings, galleries,
-- journey feeds, message book, messenger, companionships, followers/following,
-- circles, notifications, login devices and moderation (reports / blocks).
--
-- How to run (Supabase):
--   1. Supabase Dashboard → SQL Editor → New query → paste this file → Run.
--   2. or: supabase db push (copy this file into supabase/migrations/ first)
--   3. or: psql "$SUPABASE_DB_URL" -f schema.sql
--
-- Identifier convention: PascalCase (quoted) — matches the EF Core entity /
-- property names used by NeverBeen.API one-to-one, so the API works against
-- this schema with no mapping surprises.
-- ============================================================================

