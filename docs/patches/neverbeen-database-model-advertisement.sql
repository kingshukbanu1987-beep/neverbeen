-- AI model advertisement: which NeverBeen AI model portfolios are advertised on the
-- website (right rail of the Community Home + sponsored cards in the Journey feed),
-- how heavily each is rotated, and the impression / click totals the Founder reports on.
--
-- Safe to run against an existing NeverBeen database; every object is idempotent, and the
-- model pool is inserted with ON CONFLICT DO NOTHING so a weight, a switch or a counter set
-- afterwards is never overwritten. Also carried by schema.sql.

-- ---------------------------------------------------------------------------
-- NeverBeen AI model advertisement (website right rail + Journey feed)
--   The website owns the model catalog; these two tables decide which
--   portfolios take part in the advertising rotation and keep the impression /
--   click totals the founder reports on (neverbeen-api ModelAdsController).
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS "ModelAds" (
    "Id"              integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ModelSlug"       varchar(120) NOT NULL,
    "DisplayName"     varchar(160),
    "IsActive"        boolean      NOT NULL DEFAULT true,
    "Weight"          integer      NOT NULL DEFAULT 1,
    "ImpressionCount" integer      NOT NULL DEFAULT 0,
    "ClickCount"      integer      NOT NULL DEFAULT 0,
    "CreatedAtUtc"    timestamptz  NOT NULL DEFAULT now(),
    "UpdatedAtUtc"    timestamptz,
    CONSTRAINT "CK_ModelAds_ModelSlug" CHECK ("ModelSlug" ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT "CK_ModelAds_Weight" CHECK ("Weight" >= 1 AND "Weight" <= 10),
    CONSTRAINT "CK_ModelAds_Counters" CHECK ("ImpressionCount" >= 0 AND "ClickCount" >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_ModelAds_ModelSlug" ON "ModelAds" ("ModelSlug");
CREATE INDEX IF NOT EXISTS "IX_ModelAds_IsActive_Weight" ON "ModelAds" ("IsActive", "Weight" DESC);

CREATE TABLE IF NOT EXISTS "ModelAdEvents" (
    "Id"           bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ModelSlug"    varchar(120) NOT NULL,
    "EventType"    varchar(16)  NOT NULL,
    "Surface"      varchar(16)  NOT NULL,
    "ViewerId"     integer      REFERENCES "Users" ("Id") ON DELETE SET NULL,
    "CreatedAtUtc" timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT "CK_ModelAdEvents_ModelSlug" CHECK ("ModelSlug" ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT "CK_ModelAdEvents_EventType" CHECK ("EventType" IN ('impression', 'click')),
    CONSTRAINT "CK_ModelAdEvents_Surface" CHECK ("Surface" IN ('rail', 'feed'))
);

CREATE INDEX IF NOT EXISTS "IX_ModelAdEvents_ModelSlug_CreatedAtUtc"
    ON "ModelAdEvents" ("ModelSlug", "CreatedAtUtc" DESC);
CREATE INDEX IF NOT EXISTS "IX_ModelAdEvents_Surface_CreatedAtUtc"
    ON "ModelAdEvents" ("Surface", "CreatedAtUtc" DESC);
CREATE INDEX IF NOT EXISTS "IX_ModelAdEvents_ViewerId" ON "ModelAdEvents" ("ViewerId");

