-- ============================================================================
-- AI Model Live Chat counters (live now / past chats, one row per session)
-- ============================================================================
-- Each model's card shows how many chat sessions are live with her right now
-- and how many chats are already over. A row is written when a visitor's
-- two-hour chat session begins, and stamped with "EndedAtUtc" when it ends;
-- an unended row older than two hours counts as past (the session expired).
-- Safe to run against an existing NeverBeen database; every object is
-- idempotent, and databases created before the live/past split gain the new
-- columns in place.

CREATE TABLE IF NOT EXISTS "ModelLiveChatStarts" (
    "Id"           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ModelSlug"    varchar(120) NOT NULL,
    "SessionKey"   varchar(64),
    "ViewerId"     integer REFERENCES "Users" ("Id") ON DELETE SET NULL,
    "CreatedAtUtc" timestamptz NOT NULL DEFAULT now(),
    "EndedAtUtc"   timestamptz,
    CONSTRAINT "CK_ModelLiveChatStarts_ModelSlug"
        CHECK ("ModelSlug" ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);

ALTER TABLE "ModelLiveChatStarts"
    ADD COLUMN IF NOT EXISTS "SessionKey" varchar(64);

ALTER TABLE "ModelLiveChatStarts"
    ADD COLUMN IF NOT EXISTS "EndedAtUtc" timestamptz;

CREATE INDEX IF NOT EXISTS "IX_ModelLiveChatStarts_ModelSlug"
    ON "ModelLiveChatStarts" ("ModelSlug");

CREATE INDEX IF NOT EXISTS "IX_ModelLiveChatStarts_ModelSlug_SessionKey"
    ON "ModelLiveChatStarts" ("ModelSlug", "SessionKey");
