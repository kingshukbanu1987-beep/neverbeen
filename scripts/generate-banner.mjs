#!/usr/bin/env node
/** Keep the home-page people slideshow in sync with every image in public/banner. */
import { readdirSync, writeFileSync } from 'node:fs';
import { extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const bannerDir = new URL('../public/banner/', import.meta.url);
const output = new URL('../src/app/home/hero/banner-images.ts', import.meta.url);
const extensions = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif', '.gif', '.svg']);

function imagesIn(directory, prefix = '') {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = `${prefix}${entry.name}`;
    if (entry.name.startsWith('.')) return [];
    if (entry.isDirectory()) {
      return imagesIn(new URL(`${encodeURIComponent(entry.name)}/`, directory), `${path}/`);
    }
    return entry.isFile() && extensions.has(extname(entry.name).toLowerCase()) ? [path] : [];
  });
}

const sources = imagesIn(bannerDir).sort().map((path) =>
  `/banner/${path.split('/').map(encodeURIComponent).join('/')}`,
);
if (!sources.length) throw new Error('public/banner must contain at least one slideshow image.');
const content = `// Generated by scripts/generate-banner.mjs — do not edit.\nexport const BANNER_IMAGE_SOURCES: readonly string[] = ${JSON.stringify(sources, null, 2)};\n`;
writeFileSync(fileURLToPath(output), content);
console.log(`Generated home-page banner slideshow: ${sources.length} images.`);
