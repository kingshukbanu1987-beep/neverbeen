#!/usr/bin/env node
/**
 * Keep the home-page travel slideshow in sync with every image in
 * `public/travel`. Drop a photograph into that folder and re-run
 * `npm run generate:travel` (or `npm start` / `npm run build`, which do it
 * automatically) to add it to the first hero preview.
 *
 * Unlike the banner generator, this tolerates an empty folder: the first hero
 * panel then falls back to the brochure preview, so the page still has a
 * photograph until the first travel image lands.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const travelDir = new URL('../public/travel/', import.meta.url);
const output = new URL('../src/app/home/hero/travel-images.ts', import.meta.url);
const extensions = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif', '.gif', '.svg']);

function imagesIn(directory, prefix = '') {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = `${prefix}${entry.name}`;
    if (entry.name.startsWith('.')) return [];
    if (entry.isDirectory()) {
      return imagesIn(new URL(`${encodeURIComponent(entry.name)}/`, directory), `${path}/`);
    }
    return entry.isFile() && extensions.has(extname(entry.name).toLowerCase()) ? [path] : [];
  });
}

const sources = imagesIn(travelDir).sort().map((path) =>
  `/travel/${path.split('/').map(encodeURIComponent).join('/')}`,
);
const content = `// Generated by scripts/generate-travel.mjs — do not edit.\nexport const TRAVEL_IMAGE_SOURCES: readonly string[] = ${JSON.stringify(sources, null, 2)};\n`;
writeFileSync(fileURLToPath(output), content);
console.log(
  sources.length
    ? `Generated home-page travel slideshow: ${sources.length} images.`
    : 'public/travel is empty: generated an empty travel slideshow (the hero falls back to the brochure preview).',
);
